import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import zipfile
from update_integrity import update

ROOT=Path(__file__).resolve().parents[1]
IGNORED_DIRS={'.git','dist','node_modules','__pycache__'}
FORBIDDEN={'.bin','.rom','.asm','.pyc','.pem','.key','.png','.jpg','.jpeg','.wav','.mp3'}
def sha(raw):
    return hashlib.sha256(raw).hexdigest()

def collect(root):
    names=json.loads((root/'release-files.json').read_text(encoding='utf-8'))
    if not isinstance(names,list) or names!=sorted(set(names)):
        raise ValueError('release-files.json must be a sorted unique list')
    files={}
    for name in names:
        rel=PurePosixPath(name)
        if rel.is_absolute() or '..' in rel.parts or any(x in IGNORED_DIRS for x in rel.parts):
            raise ValueError('Unsafe release path: '+name)
        path=root.joinpath(*rel.parts)
        if path.suffix.lower() in FORBIDDEN or path.name.startswith(('.env','.dev.vars')) or '.wrangler' in rel.parts:
            raise ValueError('Forbidden release file: '+name)
        if any(parent.is_symlink() for parent in [path,*path.parents] if parent!=root.parent):
            raise ValueError('Symlink not allowed: '+name)
        if not path.resolve().is_relative_to(root.resolve()):
            raise ValueError('Path escapes source tree')
        raw=path.read_bytes()
        text=raw.decode('utf-8-sig')
        if re.search(r'[A-Za-z]:[\\/](?:Users|XienTiaoXiaoGo)[\\/]',text,re.I):
            raise ValueError('Private absolute path in '+name)
        if re.search(r'(?:ghp_|github_pat_)[A-Za-z0-9_]{20,}|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----',text):
            raise ValueError('Credential-like content in '+name)
        files[name]=raw
    actual={p.relative_to(root).as_posix() for p in root.rglob('*') if p.is_file()
            and not any(x in IGNORED_DIRS for x in p.relative_to(root).parts)}
    if actual!=set(names):
        raise ValueError('Unlisted or missing files: '+repr(sorted(actual^set(names))))
    return files

def source_zip(files):
    data=io.BytesIO()
    with zipfile.ZipFile(data,'w',zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for name,raw in sorted(files.items()):
            info=zipfile.ZipInfo('penc-pocket/'+name,(2026,10,28,0,0,0))
            info.compress_type=zipfile.ZIP_DEFLATED
            info.external_attr=0o100644<<16
            z.writestr(info,raw)
    return data.getvalue()

def build(root=ROOT):
    # Preflight before changing hashes: unexpected files stop publication.
    collect(root)
    update(root)
    files=collect(root)
    inventory={name:sha(raw) for name,raw in sorted(files.items())}
    release=sha(json.dumps(inventory,sort_keys=True,separators=(',',':')).encode())
    out=root/'dist'
    if out.is_symlink() or out.resolve()!=root.resolve()/'dist':
        raise ValueError('Unsafe output directory')
    if out.exists():
        if not (out/'.penc-build').is_file():
            raise ValueError('Refusing to replace an unmarked output directory')
        shutil.rmtree(out)
    out.mkdir()
    (out/'.penc-build').write_text('Generated by tools/build.py\n',encoding='utf-8')
    for name,raw in files.items():
        if name.startswith('public/'):
            dest=out/name.removeprefix('public/')
            dest.parent.mkdir(parents=True,exist_ok=True)
            if name=='public/index.html':raw=raw.replace(b'__RELEASE_ID__',release[:12].encode())
            dest.write_bytes(raw)
    (out/'licenses/GPL-3.0.txt').write_bytes(files['LICENSE'])
    (out/'.nojekyll').write_bytes(b'')
    (out/'downloads').mkdir()
    archive=source_zip(files)
    (out/'downloads/penc-pocket-source.zip').write_bytes(archive)
    relay=json.loads(re.search(r'^const configuredRelay = (.+?);',files['public/hosting.js'].decode(),re.M).group(1))
    manifest={'release_id':release,'source_zip_sha256':sha(archive),'source_files':inventory,
              'runtime':'external unmodified Pyodide 0.27.7 CDN','relay_default':'cloudflare-free-native-relay' if relay else 'disabled',
              'relay_endpoint':relay}
    (out/'release-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(json.dumps({'status':'PASS','release_id':release,'source_files':len(files),'source_zip_bytes':len(archive),'source_zip_sha256':sha(archive)}))
    return manifest

if __name__=='__main__':
    build()
